public class day03 {
    public static void main(String[] args) {
      
        // Fungsi dari \n yaitu membuat garis baru
        System.out.println("UGM:universitas gunung majene\nfakultas:teknik\nprodi:informatika");
      
        // Fungsi dari \t yaitu untuk membuat spasi/tab yang sejajar
        System.out.println("nama\t: muhammad fadhil fachry");
        System.out.println("umur\t: 18 tahun");
      
        // Fungsi dari \' yaitu menampilkan tanda petik tunggal
        System.out.println("saya dipanggil \'adil\' saat disekolah");

        // Fungsi dari \" yaitu untuk menampilkan tanda petik ganda
        System.out.println("tan malaka berkata \"padi tumbuh tak berisik\" dibuku karangannya");

        // Fungsi dari \\ yaitu untuk menampilkan karakter backslash (\)
        System.out.println("mau dipukul tangan mana\t: kanan\\kiri?");

        // Fungsi dari \r yaitu mengembalikan kursor ke awal baris untuk menimpa teks
        System.out.println("Status: kerja\rStatus: kuliah");
    }
}

